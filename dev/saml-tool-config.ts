// Writes dev/.runtime/saml-tool.config.ts (a saml-tool response config) from dev/.runtime/sandbox.json.
// Run by dev/up:  bun dev/saml-tool-config.ts <sandbox.json> <saml-tool dir> <idp base url> <output.ts>
import { resolve } from "node:path";

const [sandboxJson, samlToolDir, idpBaseUrl, outPath] = process.argv.slice(2);
if (!sandboxJson || !samlToolDir || !idpBaseUrl || !outPath) {
    console.error("usage: bun saml-tool-config.ts <sandbox.json> <saml-tool dir> <idp base url> <output.ts>");
    process.exit(2);
}

const info = await Bun.file(sandboxJson).json();
// saml-sp base64-decodes RelayState by default (encodeRelayState), so send it encoded
const relayState = Buffer.from(`${info.siteUrl}/`).toString("base64");

const config = {
    idp: {
        entityId: `${idpBaseUrl}/metadata`,
        certificatePath: resolve(samlToolDir, "certs/idp-cert.pem"),
        privateKeyPath: resolve(samlToolDir, "certs/idp-key.pem"),
    },
    sp: {
        entityId: info.sp.entityId,
        assertionConsumerServiceURL: info.sp.acsUrl,
    },
    subject: {
        nameId: "jane@example.com",
        nameIdFormat: "urn:oasis:names:tc:SAML:1.1:nameid-format:emailAddress",
    },
    attributes: {
        email: "jane@example.com",
        firstName: "Jane",
        lastName: "Doe",
        groups: ["Editors"],
    },
    // saml-sp requires both by default
    signing: { signResponse: true, signAssertion: true },
    relayState,
};

await Bun.write(
    outPath,
    `// Generated by dev/up for the saml-sp sandbox. Edit freely; regenerated on the next dev/up.\n` +
        `// Use with: dev/idp-login [saml-tool send-response options]\n` +
        `export const responseConfig = ${JSON.stringify(config, null, 4)};\n`,
);
console.log(`Wrote ${outPath}`);
